        slice="tileList.txt (stored) + overview level 2 (8x, ~240 m) of every listed tile, streamed by HTTP range reads",
        skipped="No full-resolution 30 m reads and no tiles stored (~9 GB streamed, 0 kept). The per-tile ledger stores each array's sha256.",
